-- 6. RPC ATOMIK: IMPOR MUTASI BANK (ON CONFLICT DO NOTHING)
-- ==============================================================================
CREATE OR REPLACE FUNCTION impor_mutasi_bank(
    p_akun_bank_id BIGINT,
    p_nama_file TEXT,
    p_baris JSONB
)
RETURNS JSONB AS $$
DECLARE
    v_user_id UUID;
    v_is_kas_bank BOOLEAN;
    v_aktif BOOLEAN;
    v_elem JSONB;
    v_total INT;
    v_baru INT := 0;
    v_duplikat INT := 0;
    v_tgl DATE;
    v_desc TEXT;
    v_jml BIGINT;
    v_saldo BIGINT;
    v_row_id BIGINT;
BEGIN
    -- 1. Verifikasi identitas pembuat murni dari auth.uid()
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Akses ditolak: Pengguna belum terautentikasi (auth.uid() kosong).';
    END IF;

    IF NOT auth_is_aktif() THEN
        RAISE EXCEPTION 'Akun pengguna sedang dinonaktifkan (BR-12).';
    END IF;

    IF auth_peran() <> 'akuntan' THEN
        RAISE EXCEPTION 'Hanya Akuntan yang berwenang mengimpor mutasi bank.';
    END IF;

    -- 2. Validasi Akun Kas/Bank
    SELECT is_kas_bank, aktif INTO v_is_kas_bank, v_aktif
    FROM akun
    WHERE id = p_akun_bank_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Akun bank dengan ID % tidak ditemukan.', p_akun_bank_id;
    END IF;

    IF NOT v_is_kas_bank THEN
        RAISE EXCEPTION 'Akun yang dipilih harus merupakan akun kas atau bank (is_kas_bank = true).';
    END IF;

    IF NOT v_aktif THEN
        RAISE EXCEPTION 'Akun kas/bank yang dipilih sedang tidak aktif.';
    END IF;

    -- 3. Validasi Parameter Berkas & Baris
    IF p_nama_file IS NULL OR length(trim(p_nama_file)) = 0 THEN
        RAISE EXCEPTION 'Nama file CSV wajib diisi.';
    END IF;

    IF p_baris IS NULL OR jsonb_typeof(p_baris) <> 'array' THEN
        RAISE EXCEPTION 'Data baris mutasi harus berupa array JSON.';
    END IF;

    v_total := jsonb_array_length(p_baris);
    IF v_total = 0 THEN
        RETURN jsonb_build_object('baru', 0, 'duplikat', 0);
    END IF;

    -- 4. Iterasi dan Penyisipan dalam Satu Transaksi Atomik
    FOR v_elem IN SELECT * FROM jsonb_array_elements(p_baris)
    LOOP
        v_tgl := (v_elem->>'tanggal')::DATE;
        v_desc := trim(COALESCE(v_elem->>'deskripsi', ''));
        v_jml := (v_elem->>'jumlah')::BIGINT;
        
        IF v_elem->>'saldo' IS NOT NULL AND trim(v_elem->>'saldo') <> '' THEN
            v_saldo := (v_elem->>'saldo')::BIGINT;
        ELSE
            v_saldo := NULL;
        END IF;

        IF v_tgl IS NULL THEN
            RAISE EXCEPTION 'Kolom tanggal transaksi wajib diisi.';
        END IF;

        IF length(v_desc) = 0 THEN
            RAISE EXCEPTION 'Deskripsi mutasi bank tidak boleh kosong.';
        END IF;

        IF v_jml IS NULL OR v_jml = 0 THEN
            RAISE EXCEPTION 'Jumlah mutasi bank tidak boleh bernilai 0.';
        END IF;

        -- Insert dengan klausa ON CONFLICT DO NOTHING berdasarkan constraint unik
        v_row_id := NULL;
        INSERT INTO mutasi_bank (
            akun_bank_id,
            tanggal,
            deskripsi,
            jumlah,
            saldo,
            nama_file,
            jurnal_id,
            diimpor_oleh,
            diimpor_pada
        ) VALUES (
            p_akun_bank_id,
            v_tgl,
            v_desc,
            v_jml,
            v_saldo,
            trim(p_nama_file),
            NULL,
            v_user_id,
            now()
        )
        ON CONFLICT ON CONSTRAINT uq_mutasi_bank_transaksi DO NOTHING
        RETURNING id INTO v_row_id;

        IF v_row_id IS NOT NULL THEN
            v_baru := v_baru + 1;
        END IF;
    END LOOP;

    v_duplikat := v_total - v_baru;

    RETURN jsonb_build_object('baru', v_baru, 'duplikat', v_duplikat);
END;
$$ LANGUAGE plpgsql VOLATILE SECURITY INVOKER SET search_path = public, pg_temp;

