-- 7. RPC ATOMIK: PEMBUATAN DRAF JURNAL DARI MUTASI BANK
-- ==============================================================================
CREATE OR REPLACE FUNCTION buat_draf_dari_mutasi(
    p_mutasi_id BIGINT,
    p_akun_lawan_id BIGINT
)
RETURNS jurnal AS $$
DECLARE
    v_user_id UUID;
    v_mutasi mutasi_bank%ROWTYPE;
    v_lawan_akun akun%ROWTYPE;
    v_periode periode%ROWTYPE;
    v_keterangan_final TEXT;
    v_abs_jumlah BIGINT;
    v_jurnal jurnal%ROWTYPE;
BEGIN
    -- 1. Verifikasi identitas pembuat murni dari auth.uid()
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Akses ditolak: Pengguna belum terautentikasi (auth.uid() kosong).';
    END IF;

    IF NOT auth_is_aktif() THEN
        RAISE EXCEPTION 'Akun pengguna sedang dinonaktifkan (BR-12).';
    END IF;

    IF auth_peran() <> 'akuntan' THEN
        RAISE EXCEPTION 'Hanya Akuntan yang berwenang membuat draf jurnal dari mutasi bank.';
    END IF;

    -- 2. Kunci dan validasi baris mutasi_bank (SELECT ... FOR UPDATE)
    SELECT * INTO v_mutasi
    FROM mutasi_bank
    WHERE id = p_mutasi_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Data mutasi bank dengan ID % tidak ditemukan.', p_mutasi_id;
    END IF;

    IF v_mutasi.jurnal_id IS NOT NULL THEN
        RAISE EXCEPTION 'Baris mutasi bank ini sudah memiliki jurnal terkait (Jurnal ID: %).', v_mutasi.jurnal_id;
    END IF;

    -- 3. Validasi akun lawan
    IF p_akun_lawan_id IS NULL THEN
        RAISE EXCEPTION 'Akun lawan transaksi wajib dipilih.';
    END IF;

    IF p_akun_lawan_id = v_mutasi.akun_bank_id THEN
        RAISE EXCEPTION 'Akun lawan tidak boleh sama dengan akun bank mutasi.';
    END IF;

    SELECT * INTO v_lawan_akun
    FROM akun
    WHERE id = p_akun_lawan_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Akun lawan dengan ID % tidak ditemukan.', p_akun_lawan_id;
    END IF;

    IF NOT v_lawan_akun.aktif THEN
        RAISE EXCEPTION 'Akun lawan (%) sedang tidak aktif (BR-01).', v_lawan_akun.nama;
    END IF;

    -- 4. Validasi Periode Akuntansi untuk Tanggal Mutasi (BR-05)
    SELECT * INTO v_periode
    FROM periode
    WHERE tahun = EXTRACT(YEAR FROM v_mutasi.tanggal)::INT
      AND bulan = EXTRACT(MONTH FROM v_mutasi.tanggal)::INT;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Periode akuntansi untuk tanggal mutasi (%) belum dibuat di sistem (BR-05).', v_mutasi.tanggal;
    END IF;

    IF v_periode.status <> 'terbuka' THEN
        RAISE EXCEPTION 'Jurnal hanya bisa dibuat pada periode yang berstatus terbuka (BR-05). Periode %-% sudah ditutup.',
            v_periode.tahun, lpad(v_periode.bulan::TEXT, 2, '0');
    END IF;

    -- 5. Siapkan keterangan jurnal (minimal 5 karakter sesuai BR-02/constraint jurnal)
    v_keterangan_final := trim(v_mutasi.deskripsi);
    IF length(v_keterangan_final) < 5 THEN
        v_keterangan_final := v_keterangan_final || ' (Mutasi Bank)';
    END IF;

    -- 6. Insert Header Jurnal Draf (persis pola simpan_jurnal_draf)
    INSERT INTO jurnal (
        tanggal,
        keterangan,
        sumber,
        status,
        dibuat_oleh,
        periode_id
    ) VALUES (
        v_mutasi.tanggal,
        v_keterangan_final,
        'impor_bank',
        'draf',
        v_user_id,
        v_periode.id
    ) RETURNING * INTO v_jurnal;

    -- 7. Insert Baris Jurnal Seimbang (BR-02)
    -- Aturan arah mutasi:
    -- jumlah > 0 (Uang Masuk / Penerimaan Kas):
    --   Debit: Akun Bank
    --   Kredit: Akun Lawan (Pendapatan / lainnya)
    -- jumlah < 0 (Uang Keluar / Pengeluaran Kas):
    --   Debit: Akun Lawan (Beban / lainnya)
    --   Kredit: Akun Bank
    v_abs_jumlah := abs(v_mutasi.jumlah);

    IF v_mutasi.jumlah > 0 THEN
        -- Baris 1: Bank (Debit)
        INSERT INTO jurnal_baris (
            jurnal_id, urutan, akun_id, debit, kredit, keterangan
        ) VALUES (
            v_jurnal.id, 1, v_mutasi.akun_bank_id, v_abs_jumlah, 0, v_keterangan_final
        );

        -- Baris 2: Akun Lawan (Kredit)
        INSERT INTO jurnal_baris (
            jurnal_id, urutan, akun_id, debit, kredit, keterangan
        ) VALUES (
            v_jurnal.id, 2, p_akun_lawan_id, 0, v_abs_jumlah, v_keterangan_final
        );
    ELSE
        -- Baris 1: Akun Lawan (Debit)
        INSERT INTO jurnal_baris (
            jurnal_id, urutan, akun_id, debit, kredit, keterangan
        ) VALUES (
            v_jurnal.id, 1, p_akun_lawan_id, v_abs_jumlah, 0, v_keterangan_final
        );

        -- Baris 2: Bank (Kredit)
        INSERT INTO jurnal_baris (
            jurnal_id, urutan, akun_id, debit, kredit, keterangan
        ) VALUES (
            v_jurnal.id, 2, v_mutasi.akun_bank_id, 0, v_abs_jumlah, v_keterangan_final
        );
    END IF;

    -- 8. Hubungkan mutasi_bank dengan jurnal yang baru terbentuk
    UPDATE mutasi_bank
    SET jurnal_id = v_jurnal.id
    WHERE id = v_mutasi.id;

    RETURN v_jurnal;
END;
$$ LANGUAGE plpgsql VOLATILE SECURITY INVOKER SET search_path = public, pg_temp;

